// RAII unique temp directory for integration test artifacts
struct IntegrationTempDirectory
{
    std::filesystem::path path;

    IntegrationTempDirectory(const std::string& prefix = "mode_export_test")
    {
        auto tick = std::chrono::system_clock::now().time_since_epoch().count();
        path = std::filesystem::temp_directory_path()
             / "abdaudiolab_e2e"
             / (prefix + "_" + std::to_string(tick));
        std::error_code ec;
        std::filesystem::remove_all(path, ec);
        std::filesystem::create_directories(path, ec);
    }

    ~IntegrationTempDirectory()
    {
        std::error_code ec;
        std::filesystem::remove_all(path, ec);
    }

    IntegrationTempDirectory(const IntegrationTempDirectory&) = delete;
    IntegrationTempDirectory& operator=(const IntegrationTempDirectory&) = delete;
};

