void AudioABVerificationModal::loadAudioFile(bool isReference)
{
    fileChooser = std::make_unique<juce::FileChooser>(
        isReference ? "Select Reference Audio File (Hardware)..." : "Select Candidate Audio File (Model)...",
        juce::File::getCurrentWorkingDirectory(),
        "*.wav;*.aif;*.aiff;*.flac");

    fileChooser->launchAsync(juce::FileBrowserComponent::openMode | juce::FileBrowserComponent::canSelectFiles,
        [this, isReference](const juce::FileChooser& fc) {
            auto file = fc.getResult();
            if (!file.existsAsFile()) return;

            std::unique_ptr<juce::AudioFormatReader> reader(formatManager.createReaderFor(file));
            if (reader == nullptr)
            {
                juce::AlertWindow::showMessageBoxAsync(juce::AlertWindow::WarningIcon, "File Error", "Could not decode audio file.");
                return;
            }

            juce::AudioBuffer<float> buf(static_cast<int>(reader->numChannels), static_cast<int>(reader->lengthInSamples));
            reader->read(&buf, 0, static_cast<int>(reader->lengthInSamples), 0, true, true);

            if (isReference)
                setReferenceSignal(buf, reader->sampleRate, file.getFileName());
            else
                setCandidateSignal(buf, reader->sampleRate, file.getFileName());
        });
}

void AudioABVerificationModal::synthesizeCandidateFromModel()
{
    if (refSignal.buffer.getNumSamples() == 0)
    {
        lblVerdictBadge.setText("ERROR: NO REF SIGNAL", juce::dontSendNotification);
        lblVerdictBadge.setColour(juce::Label::backgroundColourId, juce::Colour(0xfffee2e2));
        lblVerdictBadge.setColour(juce::Label::textColourId, juce::Colour(0xffdc2626));
        lblVerdictSummary.setText("Please load or measure a Reference signal (A) first to serve as excitation.", juce::dontSendNotification);
        repaint();
        return;
    }

    // Create a copy of the reference audio to process through the model
    juce::AudioBuffer<float> outputBuffer;
    outputBuffer.makeCopyOf(refSignal.buffer);

    // Initialize DSP AnalogLutFilterModule
    dsp::AnalogLutFilterModule filterModule;
    filterModule.setSmoothingTime(5.0, refSignal.sampleRate);
    filterModule.setVoiceParameters(0, 0.65f, 0.45f); // Nominal musical operating point

    const int numSamples = outputBuffer.getNumSamples();
    float* channelData = outputBuffer.getWritePointer(0);

    int modelId = comboLutModel.getSelectedId();
    juce::String modelLabel = comboLutModel.getText();

    // Map selection to official LUT array and grid size (8x8 = 64)
    const int gridSize = 8;
    const dsp::AbdBatchedPoint* lutPtr = dsp::models::mock_va_synth_moog_ladder;
    if (modelId == 2) lutPtr = dsp::models::roland_juno106_ir3109_vcf;
    else if (modelId == 3) lutPtr = dsp::models::casio_cz101_phase_distortion_resonant;
    else if (modelId == 4) lutPtr = dsp::models::behringer_pro800_cem3320_vcf;
    else if (modelId == 5) lutPtr = dsp::models::manual_eurorack_vcf_diode_ladder;
    else if (modelId == 6) lutPtr = dsp::models::roland_aira_bitrazer_filter;

    // Process in blocks of 64
    const int blockSize = 64;
    for (int offset = 0; offset < numSamples; offset += blockSize)
    {
        int curBlock = std::min(blockSize, numSamples - offset);
        float* blockPtr = channelData + offset;
        std::array<float*, 8> voicePtrs = { blockPtr, nullptr, nullptr, nullptr, nullptr, nullptr, nullptr, nullptr };
        filterModule.processPolyphonicBlock(voicePtrs.data(), curBlock, lutPtr, gridSize);
    }

    // If stereo, copy processed channel 0 to channel 1
    if (outputBuffer.getNumChannels() > 1)
    {
        outputBuffer.copyFrom(1, 0, outputBuffer, 0, 0, numSamples);
    }

    setCandidateSignal(outputBuffer, refSignal.sampleRate, "DSP Model: " + modelLabel);
    updateVerdictUi();
}

void AudioABVerificationModal::runComparison()
{
    if (refSignal.buffer.getNumSamples() == 0 || candSignal.buffer.getNumSamples() == 0)
    {
        lblVerdictBadge.setText("ERROR: MISSING SIGNAL", juce::dontSendNotification);
        lblVerdictBadge.setColour(juce::Label::backgroundColourId, juce::Colour(0xfffee2e2));
        lblVerdictBadge.setColour(juce::Label::textColourId, juce::Colour(0xffdc2626));
        lblVerdictSummary.setText("Please load both Reference (A) and Candidate (B) signals before verifying.", juce::dontSendNotification);
        repaint();
        return;
    }

    if (std::abs(refSignal.sampleRate - candSignal.sampleRate) > 1.0)
    {
        lblVerdictBadge.setText("ERROR: RATE MISMATCH", juce::dontSendNotification);
        lblVerdictBadge.setColour(juce::Label::backgroundColourId, juce::Colour(0xfffee2e2));
        lblVerdictBadge.setColour(juce::Label::textColourId, juce::Colour(0xffdc2626));
        lblVerdictSummary.setText("Sample rates differ (Ref: " + juce::String(refSignal.sampleRate, 0) + 
                                  " Hz, Cand: " + juce::String(candSignal.sampleRate, 0) + " Hz). Resampling required.", 
                                  juce::dontSendNotification);
        repaint();
        return;
    }

    math::AudioABRunContext ctx;
    ctx.runId = "ab-verify-interactive";

    math::AudioABComparatorConfig config;
    config.trimLeadingSilence = true;
    config.trimTrailingSilence = true;

    math::AudioABComparator comparator;
    lastResult = comparator.compare(refSignal, candSignal, ctx, config);

    if (lastResult.status != "ok")
    {
        lblVerdictBadge.setText("COMPARISON FAILED", juce::dontSendNotification);
        lblVerdictBadge.setColour(juce::Label::backgroundColourId, juce::Colour(0xfffee2e2));
        lblVerdictBadge.setColour(juce::Label::textColourId, juce::Colour(0xffdc2626));
        lblVerdictSummary.setText("Engine error: " + juce::String(lastResult.status), juce::dontSendNotification);
        repaint();
        return;
    }

    // Configure tolerances according to combo
    math::AudioABVerdictTolerances tolerances;
    int selectedPreset = comboTolerance.getSelectedId();
    if (selectedPreset == 2) // Strict
    {
        tolerances.minCorrelationPeak = 0.98;
        tolerances.maxRmsDeltaDb = 1.0;
        tolerances.maxSpectralDeltaDb = 1.5;
        tolerances.maxSampleOffset = 128.0;
        tolerances.minOverlapRatio = 0.98;
    }
    else if (selectedPreset == 3) // Permissive
    {
        tolerances.minCorrelationPeak = 0.85;
        tolerances.maxRmsDeltaDb = 4.0;
        tolerances.maxSpectralDeltaDb = 5.0;
        tolerances.maxSampleOffset = 1024.0;
        tolerances.minOverlapRatio = 0.90;
    }
    else // Standard (Default ±1σ)
    {
        tolerances.minCorrelationPeak = 0.92;
        tolerances.maxRmsDeltaDb = 2.0;
        tolerances.maxSpectralDeltaDb = 3.0;
        tolerances.maxSampleOffset = 512.0;
        tolerances.minOverlapRatio = 0.95;
    }

    math::AudioABVerdictEngine verdictEngine;
    lastVerdict = verdictEngine.evaluate(lastResult, tolerances);
    hasResult = true;
    btnExportReport.setEnabled(true);

    updateVerdictUi();

    if (onVerificationCompleted != nullptr)
        onVerificationCompleted(lastResult, lastVerdict);

    repaint();
}

