    // Verificación de procedencia diferenciada preservada
    REQUIRE(jsonAuto["hardware"]["id"] == "AIRA_TB3_TOUCH");
    REQUIRE(jsonAuto["hardware"]["deviceType"] == "AUTOMATED_SYSEX");

    REQUIRE(jsonManual["hardware"]["id"] == "EURORACK_DOEPFER_A120");
    REQUIRE(jsonManual["hardware"]["deviceType"] == "MANUAL_EURORACK");
    REQUIRE(jsonManual["laboratoryConditions"]["operatorNotes"] == "Operator step confirmed. Knob at 1.2 kHz.");
