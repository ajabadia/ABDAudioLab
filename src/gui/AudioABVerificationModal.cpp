void AudioABVerificationModal::exportReportJson()
{
    if (!hasResult) return;

    fileChooser = std::make_unique<juce::FileChooser>(
        "Save A/B Verification Report...",
        juce::File::getCurrentWorkingDirectory().getChildFile("ab_verification_report.json"),
        "*.json");

    fileChooser->launchAsync(juce::FileBrowserComponent::saveMode | juce::FileBrowserComponent::canSelectFiles,
        [this](const juce::FileChooser& fc) {
            auto file = fc.getResult();
            if (file.getFileExtension().isEmpty())
                file = file.withFileExtension("json");

            juce::DynamicObject::Ptr root = new juce::DynamicObject();
            root->setProperty("title", "ABDAudioLab A/B Model Verification Report");
            root->setProperty("reference", refName);
            root->setProperty("candidate", candName);

            juce::DynamicObject::Ptr verdictObj = new juce::DynamicObject();
            verdictObj->setProperty("level", juce::String(lastVerdict.level));
            verdictObj->setProperty("reasonCode", juce::String(lastVerdict.reasonCode));
            verdictObj->setProperty("triggeredRules", lastVerdict.triggeredRules.joinIntoString(", "));
            root->setProperty("verdict", juce::var(verdictObj.get()));

            juce::DynamicObject::Ptr alignObj = new juce::DynamicObject();
            alignObj->setProperty("correlationPeak", lastResult.alignment.correlationPeak);
            alignObj->setProperty("sampleOffset", lastResult.alignment.sampleOffset);
            alignObj->setProperty("timeOffsetMs", lastResult.alignment.timeOffsetMs);
            alignObj->setProperty("overlapRatio", lastResult.alignment.overlapRatio);
            root->setProperty("alignment", juce::var(alignObj.get()));

            juce::DynamicObject::Ptr timeObj = new juce::DynamicObject();
            timeObj->setProperty("rmsDeltaDb", lastResult.time.rmsDeltaDb);
            timeObj->setProperty("peakDeltaDb", lastResult.time.peakDeltaDb);
            timeObj->setProperty("residualRmsDbfs", lastResult.time.residualRmsDbfs);
            timeObj->setProperty("residualPeakDbfs", lastResult.time.residualPeakDbfs);
            timeObj->setProperty("rmse", lastResult.time.rmse);
            root->setProperty("dynamics", juce::var(timeObj.get()));

            juce::DynamicObject::Ptr specObj = new juce::DynamicObject();
            specObj->setProperty("logMagMeanAbsDiffDb", lastResult.spectral.logMagMeanAbsDiffDb);
            specObj->setProperty("spectralCentroidDeltaHz", lastResult.spectral.spectralCentroidDeltaHz);
            specObj->setProperty("lowBandDeltaDb", lastResult.spectral.lowBandDeltaDb);
            specObj->setProperty("midBandDeltaDb", lastResult.spectral.midBandDeltaDb);
            specObj->setProperty("highBandDeltaDb", lastResult.spectral.highBandDeltaDb);
            root->setProperty("spectral", juce::var(specObj.get()));

            juce::var jsonVar(root.get());
            juce::String jsonText = juce::JSON::toString(jsonVar, true);
            file.replaceWithText(jsonText);
        });
}

void AudioABVerificationModal::paint(juce::Graphics& g)
{
    // Scrim overlay
    g.fillAll(juce::Colour(0x75000000));

    // Panel background
    auto panelBounds = panel.getBounds();
    g.setColour(SoundIdTheme::bgLight);
    g.fillRoundedRectangle(panelBounds.toFloat(), 10.0f);
    g.setColour(SoundIdTheme::borderSubtle);
    g.drawRoundedRectangle(panelBounds.toFloat(), 10.0f, 1.5f);

    // Header Title and Subtitle
    g.setColour(SoundIdTheme::textPrimary);
    g.setFont(juce::FontOptions("Inter", 16.0f, juce::Font::bold));
    g.drawText("A/B Model Verification & Spectral Correlation", panelBounds.getX() + 24, panelBounds.getY() + 16, panelBounds.getWidth() - 70, 22, juce::Justification::centredLeft);

    g.setColour(SoundIdTheme::textSecondary);
    g.setFont(juce::FontOptions("Inter", 12.0f, juce::Font::plain));
    g.drawText("Contrast physical hardware capture against grey-box DSP emulation under ISO/EBU tolerances", 
               panelBounds.getX() + 24, panelBounds.getY() + 38, panelBounds.getWidth() - 70, 18, juce::Justification::centredLeft);

    // Divider line
    g.setColour(SoundIdTheme::borderSubtle);
    g.fillRect(panelBounds.getX() + 24, panelBounds.getY() + 60, panelBounds.getWidth() - 48, 1);

    // Cards rects inside panel
    int cardY = panelBounds.getY() + 310;
    int cardH = panelBounds.getBottom() - cardY - 24;
    int cardW = (panelBounds.getWidth() - 48 - 24) / 3;

    for (int i = 0; i < 3; ++i)
    {
        juce::Rectangle<int> card(panelBounds.getX() + 24 + i * (cardW + 12), cardY, cardW, cardH);
        g.setColour(SoundIdTheme::bgCard);
        g.fillRoundedRectangle(card.toFloat(), 6.0f);
        g.setColour(SoundIdTheme::borderSubtle);
        g.drawRoundedRectangle(card.toFloat(), 6.0f, 1.0f);

        g.setColour(SoundIdTheme::textPrimary);
        g.setFont(juce::FontOptions("Inter", 11.5f, juce::Font::plain));
        
        juce::String textToDraw;
        if (i == 0) textToDraw = metricsTimeText;
        else if (i == 1) textToDraw = metricsDynamicsText;
        else textToDraw = metricsSpectralText;

        g.drawFittedText(textToDraw, card.reduced(12, 10), juce::Justification::topLeft, 8);
    }
}

