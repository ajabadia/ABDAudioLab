void AudioABVerificationModal::setReferenceSignal(const juce::AudioBuffer<float>& buffer, double sampleRate, const juce::String& label)
{
    refSignal.sampleRate = sampleRate;
    refSignal.numChannels = buffer.getNumChannels();
    refSignal.originalNumSamples = buffer.getNumSamples();
    refSignal.buffer.makeCopyOf(buffer);
    refName = label;

    double durationMs = (sampleRate > 0.0) ? (buffer.getNumSamples() * 1000.0 / sampleRate) : 0.0;
    lblRefInfo.setText(label + " | " + juce::String(sampleRate, 0) + " Hz | " + 
                       juce::String(buffer.getNumSamples()) + " spls (" + juce::String(durationMs, 1) + " ms)", 
                       juce::dontSendNotification);
}

